import pool from './db.js';
import bcrypt from 'bcryptjs';

const ESQUEMA = 'public';

/**
 * Obtiene los metadatos de una columna desde information_schema.
 */
async function getColumnMeta(tabla, columna) {
  const { rows } = await pool.query(
    `SELECT data_type, is_nullable, column_default, is_identity
     FROM information_schema.columns
     WHERE table_schema = $1
       AND table_name = $2
       AND column_name = $3`,
    [ESQUEMA, tabla, columna]
  );
  return rows[0] || null;
}

/**
 * Devuelve el tipo SQL del id de usuarios para reutilizarlo en las
 * claves foráneas de las tablas auxiliares (soporta INTEGER/BIGINT).
 */
async function getTipoIdUsuario() {
  const meta = await getColumnMeta('usuarios', 'id_usuario');
  if (!meta) return 'INTEGER';
  if (meta.data_type === 'bigint') return 'BIGINT';
  if (meta.data_type === 'smallint') return 'SMALLINT';
  return 'INTEGER';
}

/**
 * Crea las tablas auxiliares que usa la autenticación si no existen.
 */
async function crearTablasFaltantes() {
  const idType = await getTipoIdUsuario();

  await pool.query(`
    CREATE TABLE IF NOT EXISTS public.codigos_2fa (
      id_codigo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      id_usuario ${idType} NOT NULL,
      codigo VARCHAR(10) NOT NULL,
      expiracion TIMESTAMPTZ NOT NULL,
      usado BOOLEAN NOT NULL DEFAULT FALSE,
      intentos SMALLINT NOT NULL DEFAULT 0,
      fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
      CONSTRAINT fk_2fa_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES public.usuarios (id_usuario)
        ON DELETE CASCADE
    )
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS public.tokens_recuperacion (
      id_token INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      id_usuario ${idType} NOT NULL,
      token VARCHAR(255) NOT NULL UNIQUE,
      expiracion TIMESTAMPTZ NOT NULL,
      usado BOOLEAN NOT NULL DEFAULT FALSE,
      fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
      CONSTRAINT fk_token_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES public.usuarios (id_usuario)
        ON DELETE CASCADE
    )
  `);

  await pool.query(`
    CREATE TABLE IF NOT EXISTS public.bitacora_accesos (
      id_bitacora INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      id_usuario ${idType} NULL,
      nombre_usuario VARCHAR(100) NULL,
      accion VARCHAR(100) NOT NULL,
      ip_origen VARCHAR(45) NULL,
      fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
      detalle TEXT NULL
    )
  `);

  await pool.query(`
    CREATE INDEX IF NOT EXISTS idx_2fa_usuario
    ON public.codigos_2fa (id_usuario)
  `);

  await pool.query(`
    CREATE INDEX IF NOT EXISTS idx_tokens_usuario
    ON public.tokens_recuperacion (id_usuario)
  `);

  await pool.query(`
    CREATE INDEX IF NOT EXISTS idx_bitacora_fecha
    ON public.bitacora_accesos (fecha DESC)
  `);
}

/**
 * Agrega columnas opcionales que pudieran faltar si las tablas se
 * importaron desde MySQL con un esquema incompleto.
 */
async function asegurarColumnasAuxiliares() {
  const columnas = [
    ['roles', 'fecha_creacion', 'TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP'],
    ['usuarios', 'fecha_creacion', 'TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP'],
    ['codigos_2fa', 'usado', 'BOOLEAN NOT NULL DEFAULT FALSE'],
    ['codigos_2fa', 'intentos', 'SMALLINT NOT NULL DEFAULT 0'],
    ['codigos_2fa', 'fecha_creacion', 'TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP'],
    ['tokens_recuperacion', 'usado', 'BOOLEAN NOT NULL DEFAULT FALSE'],
    ['tokens_recuperacion', 'fecha_creacion', 'TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP'],
    ['bitacora_accesos', 'ip_origen', 'VARCHAR(45) NULL'],
    ['bitacora_accesos', 'detalle', 'TEXT NULL'],
    ['bitacora_accesos', 'fecha', 'TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP']
  ];

  for (const [tabla, columna, definicion] of columnas) {
    try {
      await pool.query(
        `ALTER TABLE public.${tabla} ADD COLUMN IF NOT EXISTS ${columna} ${definicion}`
      );
    } catch (err) {
      console.warn(
        `   ⚠️ No se pudo verificar ${tabla}.${columna}: ${err.message}`
      );
    }
  }
}

/**
 * Garantiza que una columna PK tenga identidad/serial para poder insertar
 * sin especificar el id (caso típico al importar desde MySQL).
 */
async function asegurarIdentidad(tabla, columna) {
  const meta = await getColumnMeta(tabla, columna);
  if (!meta) return;

  const yaTieneIdentidad = meta.is_identity === 'YES';
  const yaTieneSecuencia = (meta.column_default || '').includes('nextval');
  if (yaTieneIdentidad || yaTieneSecuencia) return;

  try {
    await pool.query(
      `ALTER TABLE public.${tabla} ALTER COLUMN ${columna} SET NOT NULL`
    );
    await pool.query(
      `ALTER TABLE public.${tabla} ALTER COLUMN ${columna} ADD GENERATED BY DEFAULT AS IDENTITY`
    );
    console.log(`   ↳ Identidad agregada a ${tabla}.${columna}`);
  } catch (err) {
    console.warn(
      `   ⚠️ No se pudo agregar identidad a ${tabla}.${columna}: ${err.message}`
    );
  }
}

/**
 * Normaliza roles.permisos a JSONB (MySQL lo guardaba como TEXT/JSON).
 */
async function normalizarPermisos() {
  const meta = await getColumnMeta('roles', 'permisos');

  if (!meta) {
    await pool.query(
      'ALTER TABLE public.roles ADD COLUMN permisos JSONB NULL'
    );
    console.log('   ↳ Columna roles.permisos agregada como JSONB');
    return;
  }

  if (meta.data_type === 'jsonb') return;

  try {
    await pool.query(
      'ALTER TABLE public.roles ALTER COLUMN permisos DROP DEFAULT'
    );
    await pool.query(`
      ALTER TABLE public.roles
      ALTER COLUMN permisos TYPE JSONB
      USING (NULLIF(permisos::text, '')::jsonb)
    `);
    console.log('   ↳ roles.permisos convertido a JSONB');
  } catch (err) {
    console.warn(
      `   ⚠️ No se pudo convertir roles.permisos a JSONB: ${err.message}`
    );
  }
}

/**
 * Normaliza la columna estatus a SMALLINT (1 activo / 0 inactivo).
 * En PostgreSQL un booleano no admite comparaciones con 1 ni updates con 1.
 */
async function normalizarEstatus(tabla) {
  const meta = await getColumnMeta(tabla, 'estatus');
  if (!meta) return;

  if (['smallint', 'integer', 'bigint'].includes(meta.data_type)) return;

  try {
    const expresion = meta.data_type === 'boolean'
      ? 'CASE WHEN estatus THEN 1 ELSE 0 END'
      : 'COALESCE(estatus::int, 1)';

    await pool.query(
      `ALTER TABLE public.${tabla} ALTER COLUMN estatus DROP DEFAULT`
    );
    await pool.query(`
      ALTER TABLE public.${tabla}
      ALTER COLUMN estatus TYPE SMALLINT
      USING (${expresion})
    `);
    await pool.query(
      `ALTER TABLE public.${tabla} ALTER COLUMN estatus SET DEFAULT 1`
    );
    console.log(`   ↳ ${tabla}.estatus convertido a SMALLINT`);
  } catch (err) {
    console.warn(
      `   ⚠️ No se pudo convertir ${tabla}.estatus a SMALLINT: ${err.message}`
    );
  }
}

/**
 * Normaliza la columna usado a BOOLEAN y garantiza que nunca quede NULL
 * (causa típica de que un código recién creado se vea como "expirado").
 */
async function normalizarUsado(tabla) {
  const meta = await getColumnMeta(tabla, 'usado');
  if (!meta) return;

  if (meta.data_type !== 'boolean') {
    try {
      await pool.query(
        `ALTER TABLE public.${tabla} ALTER COLUMN usado DROP DEFAULT`
      );
      await pool.query(`
        ALTER TABLE public.${tabla}
        ALTER COLUMN usado TYPE BOOLEAN
        USING (COALESCE(usado::int, 0) <> 0)
      `);
      console.log(`   ↳ ${tabla}.usado convertido a BOOLEAN`);
    } catch (err) {
      console.warn(
        `   ⚠️ No se pudo convertir ${tabla}.usado a BOOLEAN: ${err.message}`
      );
      return;
    }
  }

  try {
    await pool.query(
      `UPDATE public.${tabla} SET usado = FALSE WHERE usado IS NULL`
    );
    await pool.query(
      `ALTER TABLE public.${tabla} ALTER COLUMN usado SET DEFAULT FALSE`
    );
    await pool.query(
      `ALTER TABLE public.${tabla} ALTER COLUMN usado SET NOT NULL`
    );
  } catch (err) {
    console.warn(
      `   ⚠️ No se pudo fijar el default de ${tabla}.usado: ${err.message}`
    );
  }
}

/**
 * Normaliza expiracion a TIMESTAMPTZ para que las comparaciones con NOW()
 * no dependan de la zona horaria de la sesión.
 */
async function normalizarExpiracion(tabla) {
  const meta = await getColumnMeta(tabla, 'expiracion');
  if (!meta || meta.data_type === 'timestamp with time zone') return;

  try {
    await pool.query(`
      ALTER TABLE public.${tabla}
      ALTER COLUMN expiracion TYPE TIMESTAMPTZ
      USING (expiracion AT TIME ZONE 'UTC')
    `);
    console.log(`   ↳ ${tabla}.expiracion convertido a TIMESTAMPTZ`);
  } catch (err) {
    console.warn(
      `   ⚠️ No se pudo convertir ${tabla}.expiracion a TIMESTAMPTZ: ${err.message}`
    );
  }
}

/**
 * Garantiza que intentos nunca quede NULL y tenga default 0.
 */
async function normalizarIntentos2FA() {
  const meta = await getColumnMeta('codigos_2fa', 'intentos');
  if (!meta) return;

  try {
    await pool.query(
      'UPDATE public.codigos_2fa SET intentos = 0 WHERE intentos IS NULL'
    );
    await pool.query(
      'ALTER TABLE public.codigos_2fa ALTER COLUMN intentos SET DEFAULT 0'
    );
  } catch (err) {
    console.warn(
      `   ⚠️ No se pudo fijar el default de codigos_2fa.intentos: ${err.message}`
    );
  }
}

/**
 * Normaliza codigos_2fa.codigo a texto (por si el esquema MySQL lo definió
 * como entero). El código se compara como cadena de 6 dígitos.
 */
async function normalizarCodigo2FA() {
  const meta = await getColumnMeta('codigos_2fa', 'codigo');
  if (!meta) return;
  if (meta.data_type === 'text' || meta.data_type.includes('char')) return;

  try {
    await pool.query(`
      ALTER TABLE public.codigos_2fa
      ALTER COLUMN codigo TYPE VARCHAR(10)
      USING (codigo::text)
    `);
    console.log('   ↳ codigos_2fa.codigo convertido a VARCHAR(10)');
  } catch (err) {
    console.warn(
      `   ⚠️ No se pudo convertir codigos_2fa.codigo a VARCHAR: ${err.message}`
    );
  }
}

/**
 * Sincroniza las secuencias con el MAX(id) real. Necesario cuando los datos
 * se importaron desde MySQL con ids explícitos.
 */
async function sincronizarSecuencias() {
  const tablas = [
    ['roles', 'id_rol'],
    ['usuarios', 'id_usuario'],
    ['codigos_2fa', 'id_codigo'],
    ['tokens_recuperacion', 'id_token'],
    ['bitacora_accesos', 'id_bitacora']
  ];

  for (const [tabla, columna] of tablas) {
    try {
      const { rows } = await pool.query(
        'SELECT pg_get_serial_sequence($1, $2) AS seq',
        [`public.${tabla}`, columna]
      );
      const secuencia = rows[0]?.seq;
      if (!secuencia) continue;

      await pool.query(
        `SELECT setval(
           $1::regclass,
           GREATEST(COALESCE(MAX(${columna}), 1), 1),
           MAX(${columna}) IS NOT NULL
         )
         FROM public.${tabla}`,
        [secuencia]
      );
    } catch (err) {
      console.warn(
        `   ⚠️ No se pudo sincronizar la secuencia de ${tabla}.${columna}: ${err.message}`
      );
    }
  }
}

/**
 * Verifica y prepara el esquema de la base de datos en Supabase/PostgreSQL.
 */
export async function initializeDatabase() {
  console.log('🔄 Verificando y preparando esquema de base de datos PostgreSQL...');

  try {
    // 1. Verificar que existan las tablas base
    const { rows: tablasBase } = await pool.query(
      `SELECT table_name
       FROM information_schema.tables
       WHERE table_schema = $1
         AND table_name IN ('roles', 'usuarios')`,
      [ESQUEMA]
    );

    const existentes = tablasBase.map((r) => r.table_name);
    for (const requerida of ['roles', 'usuarios']) {
      if (!existentes.includes(requerida)) {
        throw new Error(
          `No existe la tabla public.${requerida} en Supabase. Créala antes de iniciar el servidor.`
        );
      }
    }

    // 2. Crear tablas auxiliares si no existen
    await crearTablasFaltantes();
    await asegurarColumnasAuxiliares();

    // 3. Asegurar identidad/serial en las PK (compatibilidad con dumps MySQL)
    await asegurarIdentidad('roles', 'id_rol');
    await asegurarIdentidad('usuarios', 'id_usuario');
    await asegurarIdentidad('codigos_2fa', 'id_codigo');
    await asegurarIdentidad('tokens_recuperacion', 'id_token');
    await asegurarIdentidad('bitacora_accesos', 'id_bitacora');

    // 4. Normalizar tipos de datos para que el código use un único contrato
    await normalizarPermisos();
    await normalizarEstatus('roles');
    await normalizarEstatus('usuarios');
    await normalizarUsado('codigos_2fa');
    await normalizarUsado('tokens_recuperacion');
    await normalizarExpiracion('codigos_2fa');
    await normalizarExpiracion('tokens_recuperacion');
    await normalizarIntentos2FA();
    await normalizarCodigo2FA();

    // 5. Asignar permisos predeterminados
    const permisosPorRol = [
      {
        nombre: 'Administrador',
        permisos: [
          'usuarios', 'roles', 'clientes', 'proveedores',
          'productos', 'inventario', 'ventas', 'compras',
          'ingresos', 'gastos', 'caja', 'cxc', 'cxp',
          'reportes', 'bitacora'
        ]
      },
      {
        nombre: 'Encargado',
        permisos: [
          'clientes', 'proveedores', 'productos', 'inventario',
          'ventas', 'compras', 'ingresos', 'gastos',
          'caja', 'cxc', 'cxp'
        ]
      },
      {
        nombre: 'Vendedor',
        permisos: [
          'ventas', 'clientes', 'productos_consulta', 'caja'
        ]
      }
    ];

    for (const rol of permisosPorRol) {
      await pool.query(
        `
          UPDATE public.roles
          SET permisos = $1
          WHERE nombre = $2
            AND (
              permisos IS NULL
              OR permisos::text = 'null'
            )
        `,
        [JSON.stringify(rol.permisos), rol.nombre]
      );
    }

    // 6. Buscar al usuario administrador inicial
    const { rows: adminRows } = await pool.query(`
      SELECT id_usuario, contrasena
      FROM public.usuarios
      WHERE nombre_usuario = $1
      LIMIT 1
    `, ['admin']);

    if (adminRows.length > 0) {
      const adminUser = adminRows[0];
      const currentHash = adminUser.contrasena;

      // No reemplazar contraseñas bcrypt válidas.
      if (
        !currentHash ||
        currentHash === '$2b$12$PLACEHOLDER_HASH_CHANGE_ME' ||
        !/^\$2[aby]\$\d{2}\$/.test(currentHash)
      ) {
        console.log(
          'Generando hash bcrypt para el administrador inicial...'
        );

        const hashedPassword = await bcrypt.hash('Admin1234!', 10);

        await pool.query(`
          UPDATE public.usuarios
          SET contrasena = $1
          WHERE id_usuario = $2
        `, [hashedPassword, adminUser.id_usuario]);

        console.log(
          'Contraseña inicial del administrador actualizada.'
        );
      }
    }

    // 7. Sincronizar secuencias con los datos existentes
    await sincronizarSecuencias();

    console.log('✅ Esquema de base de datos PostgreSQL verificado y listo.');

  } catch (err) {
    console.error(
      '❌ Error al inicializar esquema de base de datos:',
      err.message
    );

    throw err;
  }
}
