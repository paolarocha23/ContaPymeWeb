/**
 * Normaliza la columna estatus a SMALLINT (1 activo / 0 inactivo).
 * En PostgreSQL un booleano no admite comparaciones con 1 ni updates con 1.
 */
async function normalizarEstatus(tabla) {
  const meta = await getColumnMeta(tabla, 'estatus');
  if (!meta) return;

  if (['smallint', 'integer', 'bigint'].includes(meta.data_type)) return;

  try {
    const expresion = meta.data_type === 'boolean'
      ? 'CASE WHEN estatus THEN 1 ELSE 0 END'
      : 'COALESCE(estatus::int, 1)';

    await pool.query(
      `ALTER TABLE public.${tabla} ALTER COLUMN estatus DROP DEFAULT`
    );
    await pool.query(`
      ALTER TABLE public.${tabla}
      ALTER COLUMN estatus TYPE SMALLINT
      USING (${expresion})
    `);
    await pool.query(
      `ALTER TABLE public.${tabla} ALTER COLUMN estatus SET DEFAULT 1`
    );
    console.log(`   ↳ ${tabla}.estatus convertido a SMALLINT`);
  } catch (err) {
    console.warn(
      `   ⚠️ No se pudo convertir ${tabla}.estatus a SMALLINT: ${err.message}`
    );
  }
}

/**
 * Normaliza la columna usado a BOOLEAN y garantiza que nunca quede NULL
 * (causa típica de que un código recién creado se vea como "expirado").
 */
async function normalizarUsado(tabla) {
  const meta = await getColumnMeta(tabla, 'usado');
  if (!meta) return;

  if (meta.data_type !== 'boolean') {
    try {
      await pool.query(
        `ALTER TABLE public.${tabla} ALTER COLUMN usado DROP DEFAULT`
      );
      await pool.query(`
        ALTER TABLE public.${tabla}
        ALTER COLUMN usado TYPE BOOLEAN
        USING (COALESCE(usado::int, 0) <> 0)
      `);
      console.log(`   ↳ ${tabla}.usado convertido a BOOLEAN`);
    } catch (err) {
      console.warn(
        `   ⚠️ No se pudo convertir ${tabla}.usado a BOOLEAN: ${err.message}`
      );
      return;
    }
  }

  try {
    await pool.query(
      `UPDATE public.${tabla} SET usado = FALSE WHERE usado IS NULL`
    );
    await pool.query(
      `ALTER TABLE public.${tabla} ALTER COLUMN usado SET DEFAULT FALSE`
    );
    await pool.query(
      `ALTER TABLE public.${tabla} ALTER COLUMN usado SET NOT NULL`
    );
  } catch (err) {
    console.warn(
      `   ⚠️ No se pudo fijar el default de ${tabla}.usado: ${err.message}`
    );
  }
}

/**
 * Normaliza expiracion a TIMESTAMPTZ para que las comparaciones con NOW()
 * no dependan de la zona horaria de la sesión.
 */
async function normalizarExpiracion(tabla) {
  const meta = await getColumnMeta(tabla, 'expiracion');
  if (!meta || meta.data_type === 'timestamp with time zone') return;

  try {
    await pool.query(`
      ALTER TABLE public.${tabla}
      ALTER COLUMN expiracion TYPE TIMESTAMPTZ
      USING (expiracion AT TIME ZONE 'UTC')
    `);
    console.log(`   ↳ ${tabla}.expiracion convertido a TIMESTAMPTZ`);
  } catch (err) {
    console.warn(
      `   ⚠️ No se pudo convertir ${tabla}.expiracion a TIMESTAMPTZ: ${err.message}`
    );
  }
}

